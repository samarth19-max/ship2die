import { Offer } from "./types";
import { discountPct, cur, campaignWord, campaignLabel } from "./renderer";
import { fmtEndInTz, fmtEndDisplay } from "./dates";

export interface KitTexts {
  draft: boolean;
  x_post: string; x_thread: string; reddit: string; discord: string; email: string; og_note: string;
}

/** Share posts point at the PUBLIC page (where the deal lives), never the checkout
    link. No public URL yet → label DRAFT and use an explicit placeholder. */
export function kitTexts(o: Offer): KitTexts {
  const pct = discountPct(o);
  const cw = campaignWord(o);
  const endStr = fmtEndInTz(o) || fmtEndDisplay(o);
  const pub = String(o.pageUrl || "").trim();
  const draft = !pub;
  const u = pub || "[PUBLISH-THEN-REPLACE: your page URL]";
  const tag = o.tag || "";
  const draftNote = "\n\n(DRAFT — placeholder link: publish your page, set its URL in the builder, then replace before posting.)";
  const hash = cw.replace(/[^A-Za-z0-9]/g, "") || "BlackFriday";
  return {
    draft,
    x_post: "🚀 " + cw + " deal is LIVE:\n\n" + (o.name || "My product") + " — " + (pct > 0 ? pct + "% off" : "on sale") + " (" + cur(o) + o.old + " → " + cur(o) + o.new + ")\n" + tag + "\n\nEnds " + endStr + ". Don't sleep on it 👇\n" + u + "\n\n#" + hash + new Date().getFullYear() + " #buildinpublic" + (draft ? draftNote : ""),
    x_thread: "1/\n" + cw + ", but for builders who hate marketing.\n\nI made " + (o.name || "my product") + ": " + (tag || "one useful thing") + "\n\nThis week only it's " + cur(o) + o.new + " instead of " + cur(o) + o.old + ".\n\nWhy I built it 🧵👇" + (draft ? "\n\n(DRAFT — finish the thread with your public page URL once it's live.)" : ""),
    reddit: "**" + (o.name || "My product") + " — " + (pct > 0 ? pct + "% off for " + cw + " (" + cur(o) + o.old + " → " + cur(o) + o.new + ")" : "on sale for " + cur(o) + o.new) + "**\n\n" + (o.desc || "") + "\n\nWhat it does:\n" + (o.feats || []).filter(Boolean).map((f) => "- " + f).join("\n") + "\n\nDeal ends " + endStr + ": " + u + "\n\nHappy to answer questions — built it solo." + (draft ? draftNote : ""),
    discord: "@everyone 🚀 " + cw + " deal: **" + (o.name || "my product") + "** — " + (pct > 0 ? pct + "% off " : "") + "(" + cur(o) + o.old + " → **" + cur(o) + o.new + "), ends " + endStr + ". " + u + "\n\nBuilt by a solo founder, would mean a lot 🙏" + (draft ? draftNote : ""),
    email: "Subject: " + (o.name || "Our") + " — " + (pct > 0 ? pct + "% off, ends " + endStr : cw + " deal inside") + "\n\nHi,\n\nQuick one: " + (o.name || "our product") + " is " + (pct > 0 ? pct + "% off" : "on sale") + " until " + endStr + " (" + cur(o) + o.old + " → " + cur(o) + o.new + ").\n\n" + tag + "\n\nGrab it here: " + u + "\n\nThat's it — happy shipping!" + (draft ? "\n\n(DRAFT — placeholder link: replace with your live page URL before sending.)" : ""),
    og_note: "og.png is referenced by your exported page. Download it from the OG banner tool (or grab it from the campaign pack), put it in the same folder as your HTML file when you deploy.",
  };
}

export function packCopyTxt(o: Offer): string {
  const K = kitTexts(o), L: string[] = [];
  L.push("LAUNCH COPY — " + (campaignLabel(o) || "Untitled campaign"));
  L.push("Generated by BF Rocket · " + new Date().toISOString());
  L.push("");
  if (K.draft) {
    L.push("STATUS: DRAFT — no public page URL is set yet.");
    L.push("Every post below contains the placeholder [PUBLISH-THEN-REPLACE: your page URL].");
    L.push("Publish index.html first, paste its URL into the builder's “Public page URL” field, then re-download this pack. Never post the placeholder.");
  } else {
    L.push("STATUS: READY — posts link to " + o.pageUrl);
  }
  L.push("");
  [["X POST", K.x_post], ["X THREAD OPENER", K.x_thread], ["REDDIT POST", K.reddit], ["DISCORD / SLACK", K.discord], ["EMAIL BLAST", K.email], ["OG IMAGE NOTE", K.og_note]].forEach((p) => {
    L.push("==== " + p[0] + (K.draft && p[0] !== "OG IMAGE NOTE" ? " — DRAFT" : "") + " ====");
    L.push(p[1]);
    L.push("");
  });
  return L.join("\n");
}

export function packChecklistTxt(o: Offer): string {
  const tz = o.tz || "device default", L: string[] = [];
  L.push("PUBLISH CHECKLIST — " + (campaignLabel(o) || "Untitled campaign"));
  L.push("Generated by BF Rocket · " + new Date().toISOString());
  L.push("");
  L.push("PART 1 — ONLY YOU CAN VERIFY THESE (no builder can check them for you)");
  L.push("");
  L.push("[ ] Open your checkout link (" + (o.url || "NOT SET") + "), complete a test purchase, and confirm it actually charges " + cur(o) + o.new + ".");
  L.push("[ ] Confirm your provider's discount/coupon is active until the deadline (" + (fmtEndInTz(o) || "no deadline set") + ").");
  L.push("[ ] Confirm the deadline timezone (" + tz + ") matches your provider's sale window.");
  L.push("");
  L.push("Remember: hiding the button or changing the page does NOT disable the payment link or change the provider's price. Only your payment provider (Lemon Squeezy / Stripe / Gumroad / Polar) controls what customers are actually charged.");
  L.push("");
  L.push("PART 2 — SHIP IT");
  L.push("");
  L.push("1. Host the folder: drag index.html + og.png (both are in this ZIP) onto netlify.com/drop — then sign up free immediately (an unclaimed Drop site is temporary and password-protected).");
  L.push("2. Optional: add your custom domain in your host's settings.");
  L.push("3. Open the live URL and verify the page: ribbon, countdown, prices, button.");
  const steps: string[] = [];
  steps.push("Click the button on the LIVE page and verify the checkout charges " + cur(o) + o.new + ".");
  if (o.guar) steps.push("Your page prints a 30-day money-back guarantee — confirm you will honor it for your product.");
  if (String(o.analytics || "").trim()) steps.push("Your analytics runs on your page — add a privacy notice / consent banner for your visitors where required.");
  steps.push("Paste your live page URL back into the builder and re-download the pack so launch-copy.txt links to the real URL.");
  steps.forEach((t, i) => { L.push((i + 1) + ". " + t); });
  L.push("Paste the live URL into the builder's “Public page URL” field, re-download this pack, and only then share the launch-copy posts (real URL, no placeholders).");
  return L.join("\n");
}
